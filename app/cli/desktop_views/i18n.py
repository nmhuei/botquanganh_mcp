@dataclass(frozen=True)
class DesktopTranslator:
    """Translate desktop presentation keys with a safe English fallback."""

    language: str = DEFAULT_UI_LANGUAGE

    def __post_init__(self) -> None:
        try:
            language = normalize_desktop_ui_language(self.language)
        except ValueError:
            language = DEFAULT_UI_LANGUAGE
        object.__setattr__(self, "language", language)

    def text(self, key: str, **values: object) -> str:
        english = MESSAGES[DEFAULT_UI_LANGUAGE].get(key, key)
        template = MESSAGES.get(self.language, {}).get(key, english)
        try:
            return template.format(**values)
        except (KeyError, ValueError):
            return english

    def with_language(self, language: str) -> "DesktopTranslator":
        return DesktopTranslator(language)


@dataclass(frozen=True)
class _Binding:
    widget: Any
    key: str
    option: str
    values: dict[str, object]


class TranslationBindings:
    """Keep static Tk widget text synchronized with a translator instance."""

    def __init__(self, translator: DesktopTranslator) -> None:
        self.translator = translator
        self._bindings: list[_Binding] = []

    def bind(
        self,
        widget: Any,
        key: str,
        *,
        option: str = "text",
        **values: object,
    ) -> None:
        binding = _Binding(widget, key, option, dict(values))
        self._bindings.append(binding)
        self._apply(binding)

    def set_translator(self, translator: DesktopTranslator) -> None:
        self.translator = translator
        for binding in self._bindings:
            self._apply(binding)

    def _apply(self, binding: _Binding) -> None:
        binding.widget.configure(
            **{binding.option: self.translator.text(binding.key, **binding.values)}
        )
